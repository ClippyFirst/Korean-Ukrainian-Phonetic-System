from __future__ import annotations

import argparse
import csv
import hashlib
import json
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CANONICAL = ROOT / "data" / "korean" / "canonical_correspondence.csv"
OVERRIDES = ROOT / "data" / "korean" / "ipa_target_overrides.csv"
OUTPUT = ROOT / "src" / "app" / "ipa_target_data.js"


def canonical_mapping_id(layer: str, input_jamo: str, ipa: str) -> str:
    key = f"{layer}|{input_jamo}|{ipa}".encode("utf-8")
    return "KUA-CAN-" + hashlib.sha1(key).hexdigest()[:12]


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream))


def build_data() -> tuple[list[dict[str, object]], dict[str, str]]:
    mappings: dict[str, dict[str, object]] = {}
    conflicts: dict[str, str] = {}
    for row in read_rows(CANONICAL):
        ipa = unicodedata.normalize("NFC", (row.get("ipa") or "").strip())
        target = (row.get("ukrainian") or "").strip()
        status = (row.get("status") or "").strip()
        if not ipa or not target or "~" in ipa or status not in {"model-selected", "provisional"}:
            continue
        layer = (row.get("layer") or "").strip()
        input_jamo = (row.get("input") or "").strip()
        mapping_id = canonical_mapping_id(layer, input_jamo, ipa)
        record: dict[str, object] = {
            "mapping_id": mapping_id,
            "source_ipa": ipa,
            "target_grapheme": target,
            "status": status,
            "scope": (row.get("scope") or "canonical-correspondence").strip(),
            "source_ref": f"data/korean/canonical_correspondence.csv#{layer}:{input_jamo}:{ipa}",
            "notes": (row.get("notes") or "").strip(),
            "mapping_source": "canonical_correspondence",
        }
        previous = mappings.get(ipa)
        if previous and previous["target_grapheme"] != target:
            conflicts[ipa] = "conflicting_canonical_correspondence"
            continue
        if previous:
            previous["correspondence_ids"].append(mapping_id)  # type: ignore[union-attr]
        else:
            record["correspondence_ids"] = [mapping_id]
            mappings[ipa] = record

    for row in read_rows(OVERRIDES):
        ipa = unicodedata.normalize("NFC", (row.get("source_ipa") or "").strip())
        target = (row.get("target_grapheme") or "").strip()
        mapping_id = (row.get("mapping_id") or "").strip()
        status = (row.get("status") or "").strip()
        if not ipa or not target or not mapping_id or status not in {"model-selected", "provisional"}:
            continue
        mappings[ipa] = {
            "mapping_id": mapping_id,
            "correspondence_ids": [mapping_id],
            "source_ipa": ipa,
            "target_grapheme": target,
            "status": status,
            "scope": (row.get("scope") or "ipa-sequence").strip(),
            "source_ref": (row.get("source_ref") or "").strip(),
            "notes": (row.get("notes") or "").strip(),
            "mapping_source": "ipa_target_overrides",
        }
        conflicts.pop(ipa, None)
    return [mappings[key] for key in sorted(mappings)], {
        key: conflicts[key] for key in sorted(conflicts)
    }


def render_module() -> str:
    mappings, conflicts = build_data()
    return (
        "/* Generated by scripts/generate_ipa_target_data.py; do not edit by hand. */\n"
        "export const IPA_TARGET_MAPPINGS = "
        + json.dumps(mappings, ensure_ascii=False, indent=2)
        + ";\nexport const IPA_MAPPING_CONFLICTS = "
        + json.dumps(conflicts, ensure_ascii=False, indent=2)
        + ";\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    args = parser.parse_args()
    expected = render_module()
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if actual != expected:
            print(f"stale generated IPA target data: {OUTPUT.relative_to(ROOT)}")
            return 1
        print("generated IPA target data is current")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
