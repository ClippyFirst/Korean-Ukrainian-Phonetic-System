#!/usr/bin/env node
/**
 * Fetch and verify the pinned, deterministic libhangul Hanja word inventory.
 *
 * The source files are pinned to an immutable HanjaKey commit and verified
 * against their Git blob SHA-1 before any generated browser data is written.
 * Only the per-file BSD-3-Clause libhangul data is used; no neural model,
 * generated ranking table, frequency corpus, or NIKL definitions are imported.
 */
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const UPSTREAM_COMMIT = '4397d39106453bf4ee71b565dfb25e98eb71580f';
export const SOURCES = Object.freeze([
  {
    name: 'hanja.txt',
    url: `https://raw.githubusercontent.com/SJY051/HanjaKey/${UPSTREAM_COMMIT}/Sources/HanjaKitCore/Resources/hanja.txt`,
    gitBlobSha1: '7cca2b4666ca19dcb10aaada52af89360c381659',
  },
  {
    name: 'hanja_words.txt',
    url: `https://raw.githubusercontent.com/SJY051/HanjaKey/${UPSTREAM_COMMIT}/Sources/HanjaKitCore/Resources/hanja_words.txt`,
    gitBlobSha1: '07a9a7fc675c82628f4bacfeb22db679ce60866f',
  },
]);

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT_PATH = path.join(ROOT, 'src/app/hanja-dictionary-data.js');

export function gitBlobSha1(bytes) {
  const buffer = Buffer.isBuffer(bytes) ? bytes : Buffer.from(bytes);
  return createHash('sha1')
    .update(`blob ${buffer.length}\0`, 'utf8')
    .update(buffer)
    .digest('hex');
}

function parseRows(text) {
  const rows = [];
  for (const rawLine of text.split(/\r?\n/u)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const columns = line.split(':');
    if (columns.length < 2) continue;
    const reading = columns.shift().trim();
    const hanja = columns.shift().trim();
    const gloss = columns.join(':').trim();
    if (!reading || !hanja) continue;
    rows.push({ reading, hanja, gloss });
  }
  return rows;
}

/** Preserve source candidate order as a stable fallback rank per reading. */
export function parseSingleCharacterRanks(text) {
  const ranks = new Map();
  for (const { reading, hanja } of parseRows(text)) {
    if ([...reading].length !== 1 || [...hanja].length !== 1) continue;
    let candidates = ranks.get(reading);
    if (!candidates) {
      candidates = new Map();
      ranks.set(reading, candidates);
    }
    if (!candidates.has(hanja)) candidates.set(hanja, candidates.size);
  }
  return ranks;
}

/**
 * Choose one reproducible candidate per multi-syllable reading.
 * Ranking follows the documented non-neural fallback: entries with a gloss
 * first, then the sum of the source-order ranks of their single-Hanja parts,
 * then the original row order. This is not contextual word-sense disambiguation.
 */
export function buildPreferredWordMap(wordText, singleRanks) {
  const best = new Map();
  let order = 0;
  for (const { reading, hanja, gloss } of parseRows(wordText)) {
    const readingChars = [...reading];
    const hanjaChars = [...hanja];
    const sourceOrder = order++;
    if (readingChars.length < 2 || readingChars.length > 6 || readingChars.length !== hanjaChars.length) continue;

    let syllableScore = 0;
    let allCharactersRanked = true;
    for (let i = 0; i < readingChars.length; i++) {
      const rank = singleRanks.get(readingChars[i])?.get(hanjaChars[i]);
      if (rank === undefined) {
        allCharactersRanked = false;
        break;
      }
      syllableScore += rank;
    }
    if (!allCharactersRanked) syllableScore = Number.MAX_SAFE_INTEGER;

    const candidate = {
      hanja,
      hasGloss: Boolean(gloss),
      syllableScore,
      sourceOrder,
    };
    const current = best.get(reading);
    const isBetter = !current
      || (candidate.hasGloss && !current.hasGloss)
      || (candidate.hasGloss === current.hasGloss && candidate.syllableScore < current.syllableScore)
      || (candidate.hasGloss === current.hasGloss && candidate.syllableScore === current.syllableScore && candidate.sourceOrder < current.sourceOrder);
    if (isBetter) best.set(reading, candidate);
  }
  return new Map([...best].map(([reading, entry]) => [reading, entry.hanja]));
}

export function renderDictionaryModule(wordMap) {
  const compactRows = [...wordMap]
    .sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)
    .map(([reading, hanja]) => `${reading}:${hanja}`)
    .join('\\n');
  return [
    '// Generated by scripts/prepare-hanja-dictionary.mjs; do not edit or commit.',
    `// Source commit: https://github.com/SJY051/HanjaKey/tree/${UPSTREAM_COMMIT}`,
    '// Data: libhangul hanja.txt + hanja_words.txt; BSD 3-Clause per-file notice.',
    '// Runtime ranking is deterministic and context-insensitive; see docs/HANJA-RESEARCH-LAYER-2026-10-29.md.',
    `export const HANJA_WORD_DATA = ${JSON.stringify(compactRows)};`,
    `export const HANJA_DICTIONARY_METADATA = Object.freeze({ sourceCommit: '${UPSTREAM_COMMIT}', wordReadingCount: ${wordMap.size}, ranking: 'gloss-first; single-character source-rank sum; stable source order' });`,
    '',
  ].join('\\n');
}

export async function prepareHanjaDictionary({ fetchImpl = globalThis.fetch, outputPath = OUTPUT_PATH } = {}) {
  if (typeof fetchImpl !== 'function') throw new Error('A fetch implementation is required to prepare the Hanja dictionary.');
  const downloaded = await Promise.all(SOURCES.map(async source => {
    const response = await fetchImpl(source.url);
    if (!response.ok) throw new Error(`Could not download ${source.name}: HTTP ${response.status}`);
    const bytes = Buffer.from(await response.arrayBuffer());
    const actual = gitBlobSha1(bytes);
    if (actual !== source.gitBlobSha1) {
      throw new Error(`Integrity check failed for ${source.name}: expected Git blob ${source.gitBlobSha1}, got ${actual}`);
    }
    return { name: source.name, text: bytes.toString('utf8') };
  }));
  const byName = new Map(downloaded.map(file => [file.name, file.text]));
  const singleRanks = parseSingleCharacterRanks(byName.get('hanja.txt'));
  const wordMap = buildPreferredWordMap(byName.get('hanja_words.txt'), singleRanks);
  if (singleRanks.size < 100 || wordMap.size < 10000) {
    throw new Error(`Unexpectedly small Hanja dictionary after parsing: ${singleRanks.size} single readings, ${wordMap.size} word readings.`);
  }
  await mkdir(path.dirname(outputPath), { recursive: true });
  const generated = renderDictionaryModule(wordMap);
  await writeFile(outputPath, generated, 'utf8');
  const bytes = Buffer.byteLength(generated);
  process.stdout.write(`Prepared deterministic Hanja dictionary: ${wordMap.size} word readings, ${singleRanks.size} single-syllable readings, ${bytes} generated bytes. Sources verified by Git blob SHA-1.\n`);
  return { wordCount: wordMap.size, singleReadingCount: singleRanks.size, outputPath, bytes };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await prepareHanjaDictionary();
}
